export type TranslationVariables = Record<string, string | number>;
export type Translator = (key: TranslationKey, variables?: TranslationVariables) => string;

export function resolveLocale(language: string): DayspannLocale {
  return language.toLowerCase().startsWith("ja") ? "ja" : "en";
}

export function createTranslator(language: string): Translator {
  const messages = resolveLocale(language) === "ja" ? JA_MESSAGES : EN_MESSAGES;
  return (key, variables = {}) => {
    let message: string = messages[key];
    for (const [name, value] of Object.entries(variables)) {
      message = message.replaceAll(`{${name}}`, String(value));
    }
    return message;
  };
}

export function durationUnit(
  locale: DayspannLocale,
  unit: "day" | "week" | "month" | "year",
  value: number
): string {
  if (locale === "ja") {
    if (unit === "day") return "日";
    if (unit === "week") return "週";
    if (unit === "month") return "ヶ月";
    return "年";
  }

  if (unit === "day") return value === 1 ? "day" : "days";
  if (unit === "week") return value === 1 ? "week" : "weeks";
  if (unit === "month") return value === 1 ? "month" : "months";
  return value === 1 ? "year" : "years";
}

/** 回数と単位を、画面に出す形にする。日本語は「8日」「5週」、英語は「8 days」「5 weeks」。 */
export function formatCountUnit(locale: DayspannLocale, value: number, unit: "day" | "week"): string {
  const label = durationUnit(locale, unit, value);
  return locale === "ja" ? `${value}${label}` : `${value} ${label}`;
}

/** 残日数ピル。日本語は「あと7日」、英語は "7 days left"（1日だけ "1 day left"）。 */
export function formatDueRemaining(locale: DayspannLocale, days: number): string {
  if (locale === "ja") return `あと${days}日`;
  return days === 1 ? "1 day left" : `${days} days left`;
}

/** 期日超過のピル。日本語は「3日超過」、英語は "3 days overdue"（1日だけ "1 day overdue"）。 */
export function formatDueOverdue(locale: DayspannLocale, days: number): string {
  if (locale === "ja") return `${days}日超過`;
  return days === 1 ? "1 day overdue" : `${days} days overdue`;
}
